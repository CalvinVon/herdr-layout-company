const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const { spawnSync } = require('node:child_process');
const script = path.join(__dirname, 'agent-publish.cjs');
assert.ok(fs.existsSync(script), 'Agent publication command must exist');
const home = fs.mkdtempSync(path.join(os.tmpdir(), 'office-publish-check-'));
try {
  const env = { ...process.env, HERDR_APP_HOME: home };
  const run = (...args) => spawnSync(process.execPath, [script, ...args], { env, encoding: 'utf8' });
  const target = path.join(home, 'report.html');
  fs.writeFileSync(target, '<h1>Report</h1>');
  const note = run('pin', '--room', 'room-a', '--title', '结论', '--text', '接口已确认');
  assert.equal(note.status, 0, note.stderr);
  const file = run('pin', '--room', 'room-a', '--title', '报告', '--file', target);
  assert.equal(file.status, 0, file.stderr);
  const listed = run('list');
  assert.equal(listed.status, 0, listed.stderr);
  const rows = JSON.parse(listed.stdout).rooms['room-a'];
  assert.equal(rows.length, 2);
  assert.ok(rows.some(card => card.kind === 'note' && card.text === '接口已确认'));
  const artifact = rows.find(card => card.kind === 'file');
  assert.equal(artifact.path, fs.realpathSync(target));
  assert.equal(run('remove', '--room', 'room-b', '--id', artifact.id).status !== 0, true);
  assert.equal(run('remove', '--room', 'room-a', '--id', artifact.id).status, 0);
  assert.equal(fs.readFileSync(target, 'utf8'), '<h1>Report</h1>');
  assert.equal(JSON.parse(run('list').stdout).rooms['room-a'].length, 1);
  assert.notEqual(run('pin', '--room', 'room-a', '--title', '坏数据', '--file', path.join(home, 'missing')).status, 0);
  env.HC_TERMINAL_ID = 't-local';
  const membership = { projectKey: 'room-b', machine: null, members: [{ terminal: 't-local' }] };
  fs.writeFileSync(path.join(home, 'shared.json'), JSON.stringify({ 'workspace.office-groups': [membership] }));
  const automatic = run('pin', '--title', '自动归属', '--text', '可见内容');
  assert.equal(automatic.status, 0, automatic.stderr);
  assert.equal(JSON.parse(automatic.stdout).roomKey, 'room-b');
  fs.writeFileSync(path.join(home, 'shared.json'), JSON.stringify({ 'workspace.office-groups': [membership, { ...membership, projectKey: 'room-c' }] }));
  assert.notEqual(run('pin', '--title', '不明确', '--text', '不能乱归属').status, 0);
  console.log('Agent publication, room isolation and source preservation checks passed.');
} finally { fs.rmSync(home, { recursive: true, force: true }); }
